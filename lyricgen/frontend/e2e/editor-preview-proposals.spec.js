import {test,expect} from '@playwright/test';
import {installEditorHarness} from './editor-harness';

test('many quality proposals stay compact and a live lyric preview remains next to editing',async({page},testInfo)=>{
 const jobId='preview-proposal';
 const segments=Array.from({length:40},(_,i)=>({segment_id:`s-${i}`,start:i*.1,end:i*.1+.09,text:`Frase ${i+1} de la canción`,review:i%5===0}));
 const api=await installEditorHarness(page,{jobId,role:'admin',editorV2:true,segments});
 const windows=Array.from({length:40},(_,i)=>({id:`w-${i}`,start:i*.1,end:i*.1+.09,current_segments:[segments[i]],proposed_segments:[{...segments[i],end:i*.1+.095}],reasons:['fixed_wrapper_padding'],suggestion_type:'timing',current_end:1,proposed_end:1.1}));
 await page.route(`**/status/${jobId}`,route=>route.fulfill({json:{job_id:jobId,status:'transcribed_pending',campaign_id:'review-campaign',campaign_item_id:'one',filename:'audio.wav',segments_revision:0,segments_json:segments}}));
 await page.route(`**/editor/${jobId}`,route=>route.request().method()==='GET'?route.fulfill({json:{job_id:jobId,revision:0,segments,original_segments:segments,lock:{active:false},quality_proposal:{id:'many-proposals',base_revision:0,status:'pending',operator_suggestion_only:true,windows}}}):route.fallback());
 await page.addLocatorHandler(page.getByRole('dialog',{name:'Nuevo editor de letras'}),async dialog=>dialog.getByRole('button',{name:'Cancelar'}).click());
 await page.setViewportSize({width:1280,height:720});
 await page.goto(`/review/${jobId}`);
 const disclosure=page.getByTestId('quality-proposal-disclosure');
 await expect(disclosure).toBeVisible();
 await expect(disclosure).not.toHaveAttribute('open');
 expect((await page.getByTestId('quality-proposal-panel').boundingBox()).height).toBeLessThan(110);
 expect(api.saves).toHaveLength(0);
 await expect(page.getByLabel("Letra de esta línea",{exact:true})).toBeInViewport();
 await disclosure.locator('summary').click();
 await expect(page.getByRole('button',{name:'Aceptar',exact:true})).toHaveCount(40);
 expect((await page.getByTestId('quality-proposal-scroll').boundingBox()).height).toBeLessThan(500);
 await disclosure.locator('summary').click();
 const field=page.getByLabel('Letra de esta línea',{exact:true});
 await page.getByTestId('campaign-line-workspace').evaluate(el=>window.scrollTo(0,el.getBoundingClientRect().top+window.scrollY-150));
 await expect(field).toBeInViewport();
 const preview=page.getByTestId('review-live-preview');
 await expect(preview).toBeInViewport();
 await page.getByTestId('review-line-1').click();
 await page.locator('audio').evaluate(a=>a.pause());
 await field.fill('Letra corregida visible en la vista previa');
 await expect(preview).toContainText(/Letra corregida visible/i);
 await expect(page.locator('audio')).toHaveCount(1);
 await page.getByRole('button',{name:'Escuchar 2 s antes',exact:true}).scrollIntoViewIfNeeded();
 await expect(page.getByRole('button',{name:'Escuchar 2 s antes',exact:true})).toBeInViewport();
 await page.getByRole('button',{name:'Duplicar línea',exact:true}).scrollIntoViewIfNeeded();
 await expect(page.getByRole('button',{name:'Duplicar línea',exact:true})).toBeInViewport();
 await field.scrollIntoViewIfNeeded();
 await page.screenshot({path:testInfo.outputPath('preview-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await field.scrollIntoViewIfNeeded();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await expect(preview).toBeVisible();
 await page.screenshot({path:testInfo.outputPath('preview-mobile.png')});
});
