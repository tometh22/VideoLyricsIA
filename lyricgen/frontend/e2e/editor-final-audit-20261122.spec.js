import {test,expect} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
import {installEditorHarness} from './editor-harness';
test('keeps a second-line correction typed during first-line proposal application',async({page},testInfo)=>{
 const jobId='synthetic-final-proposal';
 const rows=[{segment_id:'a',start:.1,end:1,text:'Primera original'},{segment_id:'b',start:2,end:3,text:'Segunda original'}];
 const proposal={id:'synthetic-proposal',base_revision:0,status:'pending',expires_at:'2099-01-01T00:00:00Z',windows:[{id:'w',start:.1,end:1,current_segments:[rows[0]],proposed_segments:[{...rows[0],text:'Primera propuesta'}],reasons:['text_mismatch']}]};
 const h=await installEditorHarness(page,{jobId,editorV2:true,role:'admin',segments:rows,qualityProposal:proposal});
 let finish,phase='before';
 await page.route(`**/editor/${jobId}`,route=>route.request().method()==='GET'?route.fulfill({json:{job_id:jobId,revision:phase==='before'?0:1,segments:phase==='before'?rows:[{...rows[0],text:'Primera propuesta'},rows[1]],original_segments:rows,lock:{active:false},quality_proposal:phase==='before'?proposal:{...proposal,status:'applied',windows:[]}}}):route.fallback());
 await page.route(`**/editor/${jobId}/quality-proposals/${proposal.id}/apply`,async route=>{await new Promise(resolve=>{finish=resolve;});phase='after';await route.fulfill({json:{ok:true}});});
 await page.goto(`/review/${jobId}`);
 await page.getByTestId('quality-proposal-disclosure').locator('summary').click();
 await page.getByTestId('quality-proposal-panel').getByRole('checkbox').first().check();
 await page.getByRole('button',{name:'Aplicar seleccionadas (1)',exact:true}).click();
 await expect.poll(()=>typeof finish).toBe('function');
 const second=page.getByRole('textbox',{name:'Letra de la línea 2',exact:true});
 await second.fill('Segunda corregida durante la espera');
 await expect(second).toHaveValue('Segunda corregida durante la espera');
 const before={text:await second.inputValue(),saves:h.saves.length};
 finish();
 await expect(page.getByRole('textbox',{name:'Letra de la línea 1',exact:true})).toHaveValue('Primera propuesta');
 const after=await page.getByRole('textbox').evaluateAll(nodes=>nodes.map(n=>n.value));
 await writeFile(testInfo.outputPath('proposal-result.json'),JSON.stringify({before,after,saves:h.saves},null,2));
 expect(before.saves).toBe(0);
 await expect(second).toHaveValue('Segunda corregida durante la espera');
});
test('moving a timed line does not preserve unusable word clocks outside its new interval',async({page},testInfo)=>{
 const jobId='synthetic-final-words';
 const rows=[{segment_id:'a',start:1.2,end:2.2,text:'hola mundo',words:[{word:'hola',start:1.2,end:1.6},{word:'mundo',start:1.6,end:2.2}]}];
 const h=await installEditorHarness(page,{jobId,editorV2:true,role:'admin',segments:rows});
 await page.addLocatorHandler(page.getByRole('dialog',{name:'Nuevo editor de letras'}),async dialog=>dialog.getByRole('button',{name:'Cancelar'}).click());
 await page.goto(`/videos/${jobId}/edit-lyrics`);
 await page.getByRole('button',{name:/4 Lyrics/}).click();
 await page.waitForFunction(()=>document.querySelector('audio')?.readyState>=1);
 await page.getByRole('tab',{name:'Ajustar tiempos',exact:true}).click();
 const body=page.getByTestId('timeline-segment-body').first();
 await body.scrollIntoViewIfNeeded();
 const box=await body.boundingBox();const px=Number(await page.getByTestId('timeline-lane').getAttribute('data-px-per-sec'));
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();
 await page.mouse.move(box.x+box.width/2-.8*px,box.y+box.height/2,{steps:10});await page.mouse.up();
 await expect.poll(()=>h.saves.some(save=>save.segments[0].start<.6)).toBe(true);
 const row=h.saves.find(save=>save.segments[0].start<.6).segments[0];
 await writeFile(testInfo.outputPath('word-move-result.json'),JSON.stringify(row,null,2));
 expect(!row.words || row.words.every(w=>row.start<=w.start&&w.start<w.end&&w.end<=row.end)).toBe(true);
});
