const lookImage = document.querySelector('#look-image');
let selectedLook = 'cosmico';
function lookAlt(key) {
  const lyric = key === 'pop' ? 'Lluvia espacial' : 'Lavará sus heridas';
  return language === 'en'
    ? looks[key].en+' style: the lyric “'+lyric+'”'+(key === 'pop' ? ' on a flat color background' : ' over a rainy alley')
    : 'Estilo '+looks[key].es+': la letra «'+lyric+'»'+(key === 'pop' ? ' sobre un fondo de color plano' : ' sobre un callejón bajo la lluvia');
}
function setLook(key) {
  selectedLook = key;
  document.querySelectorAll('[data-look]').forEach(button => {
    button.setAttribute('aria-pressed',String(button.dataset.look === key));
    button.querySelector('span').textContent = looks[button.dataset.look][language];
  });
  document.querySelector('#look-name').textContent = looks[key][language];
  const src = document.querySelector('[data-look="'+key+'"]').dataset.src;
  if (lookImage.getAttribute('src') !== src) {
    lookImage.classList.add('is-swapping');
    const next = new Image();
    next.onload = next.onerror = () => {lookImage.src = src; lookImage.classList.remove('is-swapping');};
    next.src = src;
  }
  lookImage.alt = lookAlt(key);
}
document.querySelectorAll('[data-look]').forEach(button => button.addEventListener('click',() => setLook(button.dataset.look)));

