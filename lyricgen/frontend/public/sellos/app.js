// Hero: the headline lights up word by word, like a synced lyric line.
const heroTitle = document.querySelector('[data-sync]');
const timecode = document.querySelector('#timecode');
const timecodeBar = document.querySelector('.timecode-bar');
function formatTime(seconds) {
  const whole = Math.floor(seconds);
  return String(Math.floor(whole / 60)).padStart(2,'0')+':'+String(whole % 60).padStart(2,'0')+'.'+String(Math.floor((seconds - whole) * 100)).padStart(2,'0');
}
function syncHeadline() {
  const words = heroTitle.textContent.trim().split(/\s+/);
  heroTitle.innerHTML = words.map((word,index) => '<span class="w'+(index >= words.length - 2 ? ' accent' : '')+'" style="--i:'+index+'">'+word+'</span>').join(' ');
  const total = (words.length - 1) * .34 + .8;
  if (reducedMotion) {
    timecode.textContent = formatTime(total);
    return;
  }
  document.body.classList.remove('is-syncing');
  void heroTitle.offsetWidth;
  document.body.classList.add('is-syncing');
  const start = performance.now();
  const tick = now => {
    const elapsed = Math.min((now - start) / 1000, total);
    timecode.textContent = formatTime(elapsed);
    timecodeBar.style.setProperty('--progress', String(elapsed / total));
    if (elapsed < total) requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}

// Published work reel: duplicated rows loop unless motion is reduced.
const reel = document.querySelector('[data-reel]');
const reelToggle = document.querySelector('#reel-toggle');
function setupReel() {
  if (reducedMotion) return;
  reel.querySelectorAll('.reel-track').forEach(track => {
    [...track.children].forEach(item => {
      const clone = item.cloneNode(true);
      clone.setAttribute('aria-hidden','true');
      track.appendChild(clone);
    });
  });
  reel.classList.add('is-moving');
  reelToggle.hidden = false;
}
function updateReelToggle() {
  const paused = reel.classList.contains('is-paused');
  reelToggle.setAttribute('aria-pressed',String(paused));
  reelToggle.textContent = paused ? (language === 'en' ? 'Resume' : 'Reanudar') : (language === 'en' ? 'Pause' : 'Pausar');
}
reelToggle.addEventListener('click',() => {
  reel.classList.toggle('is-paused');
  updateReelToggle();
});

