// Inquiry brief: prepared locally, sent by the visitor from their own email.
const briefForm = document.querySelector('#brief');
const briefPreview = document.querySelector('#brief-preview');
const companyInput = document.querySelector('#company');
const formStatus = document.querySelector('#form-status');
function selectedAssets() {
  return [...briefForm.querySelectorAll('input[name="assets"]:checked')].map(input => assetNames[language][input.value]);
}
function buildInquiry() {
  const company = companyInput.value.trim();
  const name = document.querySelector('#name').value.trim();
  const detail = document.querySelector('#detail').value.trim();
  const scope = briefForm.querySelector('input[name="scope"]:checked');
  const volume = document.querySelector('#volume').value;
  const date = document.querySelector('#deadline').value;
  const assets = selectedAssets().join(', ');
  const plan = briefForm.querySelector('input[name="plan"]:checked').value;
  const song = document.querySelector('#song').value.trim();
  if (language === 'en') {
    return {subject:planNames.en[plan].subject+' — '+company, body:'Hi Tomi,\n\n'+planNames.en[plan].line+'\n\nLabel/company: '+company+(name ? '\nContact: '+name : '')+'\nWe need: '+assets+(scope ? '\nFor: '+scopeNames.en[scope.value] : '')+'\nSongs per month: '+volume+'\nTarget date: '+(date || 'To be agreed')+(song ? '\nSong: '+song : '')+(detail ? '\n\nDetails:\n'+detail : '')+(plan === 'sample' ? '\n\nWhat do you need from us for the sample?' : '\n\nCould you send us what it would include, timing and price?')+'\n\nThanks'+(name ? ',\n'+name : '')+'\n'};
  }
  return {subject:planNames.es[plan].subject+' — '+company, body:'Hola Tomi, ¿cómo va?\n\n'+planNames.es[plan].line+'\n\nSello/empresa: '+company+(name ? '\nContacto: '+name : '')+'\nNecesitamos: '+assets+(scope ? '\nPara: '+scopeNames.es[scope.value] : '')+'\nCanciones por mes: '+volume+'\nFecha objetivo: '+(date || 'A acordar')+(song ? '\nCanción: '+song : '')+(detail ? '\n\nDetalle:\n'+detail : '')+(plan === 'sample' ? '\n\n¿Qué necesitan de nuestro lado para la muestra?' : '\n\n¿Nos pasás qué incluiría, para cuándo y el precio?')+'\n\nGracias'+(name ? ',\n'+name : '')+'\n'};
}
function updatePreparedInquiry() {
  const inquiry = buildInquiry();
  document.querySelector('#prepared-message').value = inquiry.body;
  document.querySelector('#open-email').href = 'mailto:tomas@genly.pro?subject='+encodeURIComponent(inquiry.subject)+'&body='+encodeURIComponent(inquiry.body);
}
briefForm.addEventListener('submit',event => {
  event.preventDefault();
  const firstAsset = briefForm.querySelector('input[name="assets"]');
  companyInput.setCustomValidity(companyInput.value.trim() ? '' : (language === 'en' ? 'Enter your label or company.' : 'Ingresá tu sello o empresa.'));
  firstAsset.setCustomValidity(selectedAssets().length ? '' : (language === 'en' ? 'Choose at least one format.' : 'Elegí al menos un formato.'));
  if (!briefForm.reportValidity()) return;
  updatePreparedInquiry();
  briefForm.hidden = true;
  briefPreview.hidden = false;
  const prepared = document.querySelector('#prepared-message');
  prepared.focus();
  prepared.scrollTop = 0;
  formStatus.textContent = language === 'en' ? 'Here’s your draft. Nothing has been sent.' : 'Listo el borrador. Todavía no se mandó nada.';
});
